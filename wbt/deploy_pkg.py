"""Package a trained mimic policy for unitree_rl_mjlab's g1_ctrl, gated on sim-to-sim.

    python -m wbt.deploy_pkg --run-dir third_party/unitree_rl_mjlab/logs/rsl_rl/g1_tracking/<date_time> \
        --motion-npz third_party/unitree_rl_mjlab/src/motions/g1/ayyala_gmr.npz --name ayyala_gmr \
        [--unitree-repo third_party/unitree_rl_mjlab] [--suite full] [--no-install]

1. Reads the mjlab metadata attached to ``<run>.onnx`` (joint order, gains, default pose, action
   scale, observation order) and writes deploy.yaml from it: never hand-copy those numbers.
2. Stages exported/policy.onnx(.data), params/deploy.yaml and params/<name>.npz under wbt_deploy/<name>/.
3. Runs wbt.sim2sim on exactly those staged files (hashes recorded in the report).
4. Only on PASS: copies the folder to deploy/robots/g1/config/policy/mimic/<name>/ and writes the
   config.yaml FSM snippet to add by hand (this script does not edit config.yaml).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path

import numpy as np

from g1dance.joints import G1_JOINT_NAMES
from . import sim2sim
from .deploy_policy import onnx_metadata

TERM_MAP = {"command": ("motion_command", 58), "motion_anchor_ori_b": ("motion_anchor_ori_b", 6),
            "base_ang_vel": ("base_ang_vel", 3), "joint_pos": ("joint_pos_rel", 29),
            "joint_vel": ("joint_vel_rel", 29), "actions": ("last_action", 29)}
ROOT = Path(__file__).resolve().parents[1]


def fmt(v):
    return "[" + ", ".join(f"{x:.6g}" for x in v) + "]"


def deploy_yaml_from_metadata(meta: dict, step_dt=0.02, clip_ranges=None) -> str:
    """deploy.yaml text. ``clip_ranges`` (29, 2): clamp joint targets to the hard joint range (a target
    past a stop only pushes into the stop); verified by the sim-to-sim gates like everything else."""
    names = list(meta["joint_names"])
    if names != list(G1_JOINT_NAMES):
        raise ValueError("policy joint order != SDK order; extend this tool with a joint_ids_map before deploying")
    obs = list(meta["observation_names"])
    unknown = [o for o in obs if o not in TERM_MAP]
    if unknown:
        raise ValueError(f"observation terms without a deploy implementation: {unknown} (State_Mimic has no "
                         "motion_anchor_pos_b / base_lin_vel: train the No-State-Estimation task)")
    default = np.asarray(meta["default_joint_pos"], float)
    lines = ["# Generated by wbt.deploy_pkg from mjlab ONNX metadata. Do not edit by hand.",
             f"joint_ids_map: {list(range(29))}", f"step_dt: {step_dt}",
             f"stiffness: {fmt(meta['joint_stiffness'])}", f"damping: {fmt(meta['joint_damping'])}",
             f"default_joint_pos: {fmt(default)}", "commands: {}", "actions:", "  JointPositionAction:",
             "    clip: " + ("null" if clip_ranges is None else
                             "[" + ", ".join(fmt(r) for r in np.asarray(clip_ranges, float)) + "]"),
             "    joint_names: [.*]", f"    scale: {fmt(meta['action_scale'])}",
             f"    offset: {fmt(default)}", "    joint_ids: null", "observations:"]
    for o in obs:
        name, dim = TERM_MAP[o]
        params = "{command_name: motion}" if name in ("motion_command", "motion_anchor_ori_b") else "{}"
        lines += [f"  {name}:", f"    params: {params}", "    clip: null", f"    scale: {fmt([1.0] * dim)}",
                  "    history_length: 1"]
    return "\n".join(lines) + "\n"


def find_exports(run_dir: Path):
    meta = run_dir / f"{run_dir.name}.onnx"
    policy = run_dir / "policy.onnx"
    for f in (meta, policy):
        if not f.is_file():
            raise FileNotFoundError(f"{f} missing: mjlab writes both on every checkpoint save")
    return policy, meta


def config_snippet(name, duration, state_id):
    state = "Mimic_" + "".join(w.capitalize() for w in name.split("_"))
    return f"""# Add to deploy/robots/g1/config/config.yaml (by hand, after reading it):
#   FSM._:  {state}: {{id: {state_id}, type: Mimic}}
#   FSM.Velocity.transitions:  {state}: <choose a button combo not used elsewhere>
  {state}:
    transitions:
      Passive: LT + B.on_pressed
      Velocity: RT + A.on_pressed
    motion_file: config/policy/mimic/{name}/params/{name}.npz
    policy_dir: config/policy/mimic/{name}/
    time_start: 0.0
    time_end: {duration:.2f}   # whole prepared clip: stance -> dance -> stance, then back to Velocity
    end_state: Velocity
"""


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--run-dir", type=Path, required=True)
    p.add_argument("--motion-npz", type=Path, required=True)
    p.add_argument("--name", required=True)
    p.add_argument("--unitree-repo", type=Path, default=ROOT / "third_party/unitree_rl_mjlab")
    p.add_argument("--suite", choices=["quick", "full"], default="full")
    p.add_argument("--state-id", type=int, default=6)
    p.add_argument("--no-install", action="store_true")
    p.add_argument("--xml")
    a = p.parse_args(argv)
    if not a.name.replace("_", "").isalnum():
        p.error("--name: letters, digits and underscores only")
    policy, meta_onnx = find_exports(a.run_dir)
    meta = onnx_metadata(meta_onnx)
    stage = ROOT / "wbt_deploy" / a.name
    if stage.exists():
        shutil.rmtree(stage)
    (stage / "exported").mkdir(parents=True)
    (stage / "params").mkdir()
    for f in policy.parent.glob("policy.onnx*"):
        shutil.copy2(f, stage / "exported" / f.name)
    from .g1model import build_model

    hard = build_model(a.xml).jnt_range[1:30]
    (stage / "params" / "deploy.yaml").write_text(deploy_yaml_from_metadata(meta, clip_ranges=hard))
    shutil.copy2(a.motion_npz, stage / "params" / f"{a.name}.npz")
    report_dir = stage / "sim2sim"
    args = ["--policy", str(stage / "exported/policy.onnx"), "--deploy-yaml", str(stage / "params/deploy.yaml"),
            "--motion", str(stage / "params" / f"{a.name}.npz"), "--onnx-meta", str(meta_onnx),
            "--suite", a.suite, "--out", str(report_dir)] + (["--xml", a.xml] if a.xml else [])
    status = sim2sim.main(args)
    report = json.loads((report_dir / "report.json").read_text())
    for key, f in (("policy", stage / "exported/policy.onnx"), ("deploy_yaml", stage / "params/deploy.yaml"),
                   ("motion", stage / "params" / f"{a.name}.npz")):
        if report["sha256"][key] != hashlib.sha256(f.read_bytes()).hexdigest():
            raise RuntimeError(f"{key} changed after testing; rerun")
    if status != 0 or not report["ready_for_hardware_gantry_test"]:
        print(f"\nNOT installed: sim-to-sim failed. See {report_dir / 'report.md'}")
        return 1
    with np.load(stage / "params" / f"{a.name}.npz") as z:
        duration = len(z["joint_pos"]) / 50.0
    snippet = config_snippet(a.name, duration, a.state_id)
    (stage / "config_snippet.yaml").write_text(snippet)
    if a.no_install:
        print(f"\nPASS. Staged (not installed): {stage}")
        return 0
    dest = a.unitree_repo / "deploy/robots/g1/config/policy/mimic" / a.name
    if dest.exists():
        shutil.rmtree(dest)
    shutil.copytree(stage, dest, ignore=shutil.ignore_patterns("sim2sim", "config_snippet.yaml"))
    print(f"\nPASS. Installed {dest}\nAdd the FSM entry from {stage / 'config_snippet.yaml'}, rebuild g1_ctrl, then "
          "follow the hardware trial ladder in wbt/README.md (gantry first).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
